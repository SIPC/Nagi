package api

import (
	"strings"

	"golang.org/x/text/unicode/norm"
)

// nameSkeleton 返回节点名称的「骨架」，只用来判断两个名称是不是重名，不改显示的名称：
//
//  1. 按 cleanNodeName 整理（去掉不可见字符，空格合并）。
//  2. NFKD 分解：全角字母数字（ｗｅｂ－１）、数学字母（𝗐𝖾𝖻）、罗马数字（Ⅰ）、连字（ﬁ）这些兼容字符变成普通的拉丁字母和数字；
//     带附加符号的字母拆成字母加组合符号，é 和 e+U+0301 一样。
//  3. 按 confusables 把和拉丁字母、数字长得一样的字符换掉，再整理一次（分解可能产生空格）。
//
// confusables 是自己维护的一张小表，不是 Unicode 的完整 confusables.txt（标准库和现有依赖里都没有）。覆盖：
//   - 西里尔字母里和 a–z、A–Z、0–9 形近的（а е о р с у х ѕ і ј һ ԁ ԛ ԝ ӏ ү ѵ ѡ，А В Е К М Н О Р С Т Х У Ү Ѕ І Ӏ Ј Ԛ Ԝ Ѵ，З→3、б→6）；
//     带附加符号的（ё ї ӧ 等）经 NFKD 拆开后同样换。
//   - 希腊字母里和拉丁字母形近的（Α Β Ε Ζ Η Ι Κ Μ Ν Ο Ρ Τ Υ Χ Ϲ Ϳ Ϝ，α ο ν ι ρ υ γ ϲ ϳ）。
//   - 几个常见的：拉丁字母的变体（ı ȷ ɑ ɡ）、亚美尼亚字母（օ ս հ ո）、和连字符形近的标点（‐ ‒ – − ⁃ ˗；‑、全角的 －、单点前导符 ․ 这些经 NFKD 已经变成 - 和 .）。
//
// 没有覆盖的：拉丁字母和数字之间的形近（l、I、1，O、0，rn、m）、切罗基字母等别的文字、小型大写字母。
// 覆盖不到的形近字不算重名，批准节点前以节点 ID 和来源地址为准（见 docs/control-plane.md#接入码）。
func nameSkeleton(name string) string {
	s := norm.NFKD.String(cleanNodeName(name))
	s = strings.Map(func(r rune) rune {
		if m, ok := confusables[r]; ok {
			return m
		}
		return r
	}, s)
	return cleanNodeName(s)
}

// confusables 把形近字换成长得一样的拉丁字母、数字或标点（覆盖范围见 nameSkeleton）。
// 只列 NFKD 之后还会出现的字符：全角、数学字母这些已经分解成普通字母。
var confusables = map[rune]rune{
	// 西里尔字母，大写。
	'\u0410': 'A', '\u0412': 'B', '\u0415': 'E', '\u041a': 'K', '\u041c': 'M', '\u041d': 'H', '\u041e': 'O', '\u0420': 'P', '\u0421': 'C', '\u0422': 'T',
	'\u0425': 'X', '\u0423': 'Y', '\u04ae': 'Y', '\u0405': 'S', '\u0406': 'I', '\u04c0': 'I', '\u0408': 'J', '\u051a': 'Q', '\u051c': 'W', '\u0474': 'V',
	'\u0417': '3',
	// 西里尔字母，小写。
	'\u0430': 'a', '\u0435': 'e', '\u043e': 'o', '\u0440': 'p', '\u0441': 'c', '\u0443': 'y', '\u0445': 'x', '\u0455': 's', '\u0456': 'i', '\u0458': 'j',
	'\u04bb': 'h', '\u0501': 'd', '\u051b': 'q', '\u051d': 'w', '\u04cf': 'l', '\u04af': 'y', '\u0475': 'v', '\u0461': 'w', '\u0431': '6',
	// 希腊字母，大写。
	'\u0391': 'A', '\u0392': 'B', '\u0395': 'E', '\u0396': 'Z', '\u0397': 'H', '\u0399': 'I', '\u039a': 'K', '\u039c': 'M', '\u039d': 'N', '\u039f': 'O',
	'\u03a1': 'P', '\u03a4': 'T', '\u03a5': 'Y', '\u03a7': 'X', '\u03f9': 'C', '\u037f': 'J', '\u03dc': 'F',
	// 希腊字母，小写。
	'\u03b1': 'a', '\u03bf': 'o', '\u03bd': 'v', '\u03b9': 'i', '\u03c1': 'p', '\u03c5': 'u', '\u03b3': 'y', '\u03f2': 'c', '\u03f3': 'j',
	// 拉丁字母的变体。
	'\u0131': 'i', '\u0237': 'j', '\u0251': 'a', '\u0261': 'g',
	// 亚美尼亚字母。
	'\u0585': 'o', '\u057d': 'u', '\u0570': 'h', '\u0578': 'n',
	// 和连字符形近的标点（U+2011 不断行连字符经 NFKD 变成 U+2010）。
	'\u2010': '-', '\u2012': '-', '\u2013': '-', '\u2212': '-', '\u2043': '-', '\u02d7': '-',
}
